CREATE TABLE inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL DEFAULT 0,
    min_stock_level INTEGER NOT NULL DEFAULT 0,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventories_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT fk_inventories_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),

    CONSTRAINT uk_inventories_product_warehouse
        UNIQUE (product_id, warehouse_id),

    CONSTRAINT chk_inventories_quantity_nonnegative
        CHECK (quantity >= 0),

    CONSTRAINT chk_inventories_min_stock_nonnegative
        CHECK (min_stock_level >= 0)
);

CREATE INDEX idx_inventories_warehouse_product
    ON inventories (warehouse_id, product_id);

