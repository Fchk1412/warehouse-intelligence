CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    inventory_id BIGINT NOT NULL,

    movement_type VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL,
    reason VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventory_movements_inventory
        FOREIGN KEY (inventory_id) REFERENCES inventories (id),

    CONSTRAINT chk_inventory_movements_quantity_positive
        CHECK (quantity > 0),

    CONSTRAINT chk_inventory_movements_type
        CHECK (movement_type IN ('IN', 'OUT'))
);

CREATE INDEX idx_inventory_movements_inventory_created
    ON inventory_movements (inventory_id, created_at DESC);

