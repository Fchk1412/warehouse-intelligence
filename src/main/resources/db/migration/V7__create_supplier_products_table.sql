CREATE TABLE supplier_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    supplier_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    supply_price NUMERIC(12, 2) NOT NULL,
    lead_time_days INTEGER,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_supplier_products_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers (id),

    CONSTRAINT fk_supplier_products_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT uk_supplier_products_supplier_product
        UNIQUE (supplier_id, product_id),

    CONSTRAINT chk_supplier_products_price_nonnegative
        CHECK (supply_price >= 0),

    CONSTRAINT chk_supplier_products_lead_time
        CHECK (lead_time_days IS NULL OR lead_time_days > 0)
);

CREATE INDEX idx_supplier_products_product
    ON supplier_products (product_id);

