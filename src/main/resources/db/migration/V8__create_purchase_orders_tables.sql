CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    supplier_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    received_at TIMESTAMPTZ,

    CONSTRAINT fk_purchase_orders_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers (id),

    CONSTRAINT fk_purchase_orders_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),

    CONSTRAINT chk_purchase_orders_status
        CHECK (status IN ('PENDING', 'APPROVED', 'RECEIVED', 'CANCELLED'))
);

CREATE TABLE purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,

    CONSTRAINT fk_po_items_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE CASCADE,

    CONSTRAINT fk_po_items_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT uk_po_items_order_product
        UNIQUE (purchase_order_id, product_id),

    CONSTRAINT chk_po_items_quantity_positive
        CHECK (quantity > 0),

    CONSTRAINT chk_po_items_unit_price_nonnegative
        CHECK (unit_price >= 0)
);

CREATE INDEX idx_purchase_orders_supplier
    ON purchase_orders (supplier_id);

CREATE INDEX idx_purchase_orders_warehouse
    ON purchase_orders (warehouse_id);

CREATE INDEX idx_purchase_orders_status
    ON purchase_orders (status);

